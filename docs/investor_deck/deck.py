# ── Slide 5/6/12 — Engine card grid helper ──────────────────────────────────
def engine_slide(n, kicker_txt, title_txt, cards, note):
    s = add_slide()
    kicker(s, kicker_txt)
    title(s, title_txt)
    cols = 3
    gap = Inches(0.22)
    cw = (Inches(11.93) - gap * (cols - 1)) / cols
    ch = Inches(2.3)
    x0, y0 = Inches(0.7), Inches(1.85)
    for i, (t, d, status) in enumerate(cards):
        col, row = i % cols, i // cols
        x = x0 + col * (cw + gap)
        y = y0 + row * (ch + gap)
        module_card(s, x, y, cw, ch, t, d, status)
    slide_number(s, n)
    set_notes(s, note)
    return s


