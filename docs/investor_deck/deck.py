# ── Core helpers ─────────────────────────────────────────────────────────────
def add_slide():
    slide = prs.slides.add_slide(BLANK)
    sp = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, SW, SH)
    sp.fill.solid()
    sp.fill.fore_color.rgb = C(BG)
    sp.line.fill.background()
    sp.shadow.inherit = False
    slide.shapes._spTree.remove(sp._element)
    slide.shapes._spTree.insert(2, sp._element)
    return slide


def set_notes(slide, text):
    slide.notes_slide.notes_text_frame.text = text


def textbox(slide, x, y, w, h, text, size=18, color=WHITE, bold=False,
            align=PP_ALIGN.LEFT, font=FONT, anchor=MSO_ANCHOR.TOP,
            line_spacing=1.0, italic=False):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    lines = text.split("\n")
    for i, ln in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.line_spacing = line_spacing
        r = p.add_run()
        r.text = ln
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.italic = italic
        r.font.name = font
        r.font.color.rgb = C(color)
    return tb


def rect(slide, x, y, w, h, fill=None, line_color=None, line_w=1.0, radius=None, shadow=False):
    shape_type = MSO_SHAPE.ROUNDED_RECTANGLE if radius is not None else MSO_SHAPE.RECTANGLE
    sp = slide.shapes.add_shape(shape_type, x, y, w, h)
    if radius is not None:
        try:
            sp.adjustments[0] = radius
        except Exception:
            pass
    if fill is not None:
        sp.fill.solid()
        sp.fill.fore_color.rgb = C(fill)
    else:
        sp.fill.background()
    if line_color is not None:
        sp.line.color.rgb = C(line_color)
        sp.line.width = Pt(line_w)
    else:
        sp.line.fill.background()
    sp.shadow.inherit = shadow
    return sp


def picture_fit(slide, path, x, y, max_w, max_h, align="center"):
    im = Image.open(path)
    iw, ih = im.size
    scale = min(max_w / iw, max_h / ih)
    w = int(iw * scale)
    h = int(ih * scale)
    px = x + (max_w - w) // 2 if align == "center" else x
    py = y + (max_h - h) // 2
    return slide.shapes.add_picture(path, px, py, width=Emu(int(w)), height=Emu(int(h)))


def kicker(slide, text, x=Inches(0.7), y=Inches(0.42), color=CYAN):
    textbox(slide, x, y, Inches(10), Inches(0.35), text.upper(), size=13, color=color,
            bold=True, font=FONT_SEMI)


def title(slide, text, x=Inches(0.7), y=Inches(0.72), size=30, w=Inches(11.9), h=Inches(0.9)):
    textbox(slide, x, y, w, h, text, size=size, color=WHITE, bold=True, font=FONT_SEMI)


def slide_number(slide, n):
    textbox(slide, Inches(12.15), Inches(7.12), Inches(1.0), Inches(0.3),
            f"{n:02d} / {TOTAL_SLIDES}", size=10, color=MUTED2, align=PP_ALIGN.RIGHT)
    textbox(slide, Inches(0.7), Inches(7.12), Inches(3.0), Inches(0.3),
            "ORBIC", size=10, color=MUTED2, bold=True, font=FONT_SEMI)


def status_pill(slide, x, y, status, w=Inches(1.85), h=Inches(0.34)):
    color, label = STATUS[status]
    rect(slide, x, y, w, h, fill=None, line_color=color, line_w=1.25, radius=0.5)
    textbox(slide, x, y, w, h, label, size=10.5, color=color, bold=True, font=FONT_SEMI,
            align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)


def module_card(slide, x, y, w, h, title_txt, desc, status, accent=CYAN):
    rect(slide, x, y, w, h, fill=PANEL, line_color=BORDER, line_w=1.0, radius=0.06)
    rect(slide, x, y, Inches(0.06), h, fill=accent)
    textbox(slide, x + Inches(0.22), y + Inches(0.16), w - Inches(0.44), Inches(0.4),
            title_txt, size=15, color=WHITE, bold=True, font=FONT_SEMI)
    textbox(slide, x + Inches(0.22), y + Inches(0.58), w - Inches(0.44), h - Inches(1.0),
            desc, size=11.5, color=MUTED, line_spacing=1.12)
    pw = Inches(1.7)
    status_pill(slide, x + w - pw - Inches(0.2), y + h - Inches(0.5), status, w=pw, h=Inches(0.32))


def bullet_list(slide, x, y, w, items, size=14, gap=Inches(0.36), color=WHITE, marker_color=CYAN):
    cy = y
    for it in items:
        rect(slide, x, cy + Inches(0.09), Inches(0.09), Inches(0.09), fill=marker_color, radius=0.5)
        textbox(slide, x + Inches(0.28), cy, w - Inches(0.28), gap, it, size=size, color=color,
                line_spacing=1.08)
        cy += gap
    return cy


